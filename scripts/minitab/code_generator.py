TEMPLATE_MARKER = "# --- generated by minitab skill ---"


def split_command_lines(command: str) -> list[str]:
    """Normalise a session command into the form Minitab's COM API accepts.

    Verified on Minitab 22.1 (see runtime/evidence/capa_verified.md):

    * A command WITH subcommands must be a SINGLE string with the subcommands
      joined by ';' and terminated by '.', e.g.  ``CAPA C1 1; LSPEC 9; USPEC 17.``
      Sending the pieces as separate ExecuteCommand calls makes Minitab treat
      ``LSPEC 9;`` as an unknown command (``未知 Minitab 命令: LSPEC``); sending
      them as one multi-line string makes it execute ``C1`` as a command.
    * A command WITHOUT subcommands is sent as-is (optionally without the '.').

    So: multi-line input is collapsed into one line, spaces normalised.
    """
    parts: list[str] = []
    for line in command.strip("\n").splitlines():
        line = line.strip()
        if not line:
            continue
        if line.endswith("."):
            parts.append(line[:-1].strip())
            break
        parts.append(line.rstrip(";").strip())
    if not parts:
        return [command.strip()]
    return ["; ".join(parts) + "."]


@dataclass
class GenerationResult:
    session_commands: list[str]
    python_code: str
    command_used: str
    rationale: list[str]
    context_used: dict


def _columns(intent: MinitabIntent) -> list[str]:
    return intent.target_columns or ["C1"]


def _num(params: dict, key: str, default: float) -> float:
    v = params.get(key, default)
    try:
        return float(v)
    except (TypeError, ValueError):
        return default


class MinitabCodeGenerator:
    """Builds (a) Minitab session commands and (b) a standalone Python COM script."""

    def __init__(self, kb: KnowledgeBase):
        self.kb = kb

    # ------------------------------------------------------------ command gen
    def build_session_commands(self, intent: MinitabIntent) -> tuple[list[str], list[str]]:
        cat = intent.analysis_category
        p = intent.parameters or {}
        cols = _columns(intent)
        col_list = " ".join(cols)
        notes: list[str] = []
        cmds: list[str] = []

        if cat == "capability":
            # Official syntax: CAPA [C...C E]  (columns, then subgroup size as constant or column)
            # subcommands: LSPEC / USPEC / TARGET / ... all on ONE line, ';' separated, '.' terminated.
            k = int(_num(p, "subgroup", 1))
            sub_lines: list[str] = []
            if "lsl" in p:
                sub_lines.append(f"LSPEC {_num(p,'lsl',0):g}")
            if "usl" in p:
                sub_lines.append(f"USPEC {_num(p,'usl',0):g}")
            if "target" in p:
                sub_lines.append(f"TARGET {_num(p,'target',0):g}")
            if not sub_lines:
                # Minitab requires at least USPEC or LSPEC; degrade instead of emitting a
                # command that is guaranteed to fail with "1 变元太少".
                raise ValueError(
                    "CAPA 需要至少一个规格限（LSL/USL）。请在请求中给出，例如："
                    "'capability C1 LSL=9 USL=17 subgroup 1'"
                )
            cmds.append(f"CAPA {col_list} {k}; " + "; ".join(sub_lines) + ".")
            notes.append(
                "CAPA 单行形式：主命令与子命令用 ';' 分隔、以 '.' 结束（真机验证通过，"
                "分成多次调用会报 '未知命令: LSPEC'）"
            )
            notes.append(
                "CAPA 官方语法（Minitab 会话命令参考）：CAPA [C...C E]，E = 子组大小（常量或列）；"
                "规格限用 LSPEC/USPEC，均值/标准差用 MU/SIGMA，图形可用 NOCHART/GSAVE"
            )
        elif cat == "spc":
            k = int(_num(p, "subgroup", 5))
            cmds.append(f"XBR {col_list} {k}.")
            cmds.append(f"NOTE 子组大小={k}，控制图常数按子组大小自动选择")
            notes.append("XBR 需要子组大小 K；数据顺序必须为时间顺序")
        elif cat == "msa":
            cmds.append(f"GAGE {col_list}.")
            notes.append("GAGE 需要测量值/部件/操作员三列（用 ANOVA 法）")
        elif cat == "descriptive":
            cmds.append(f"DESCRIBE {col_list}.")
            notes.append("DESCRIBE 输出 N/均值/中位数/标准差/最小最大/Q1 Q3")
        elif cat == "ttest":
            if len(cols) >= 2:
                cmds.append(f"TWOSAMPLE 0.95 {cols[0]} {cols[1]}.")
                notes.append("两列独立样本 → TWOSAMPLE")
            else:
                cmds.append(f"ONET 0.95 0 {col_list}.")
                notes.append("单列 → ONET（单样本 t），检验均值默认 0，可按需写入 parameters.test_mean")
        elif cat == "anova":
            cmds.append(f"ANOVA {col_list}.")
        elif cat == "regression":
            if len(cols) >= 2:
                cmds.append(f"REGRESS {cols[0]} {len(cols)-1} {' '.join(cols[1:])}.")
                notes.append("REGRESS 语法：响应 预测变量个数 预测变量…")
            else:
                cmds.append(f"REGRESS {col_list} 1 {col_list}.")
                notes.append("缺少预测变量，已回退为响应=自身，请在意图中补充列")
        elif cat == "histogram":
            cmds.append(f"HISTOGRAM {col_list}.")
        elif cat == "boxplot":
            cmds.append(f"BOXPLOT {col_list}.")
        elif cat == "scatterplot":
            if len(cols) >= 2:
                cmds.append(f"PLOT {cols[0]} * {cols[1]}.")
            else:
                cmds.append(f"PLOT {cols[0]} * {cols[0]}.")
        elif cat == "run_chart":
            cmds.append(f"RUNCHART {col_list}.")
        elif cat == "doe":
            cmds.append("FACTORIAL 2 3 2.")
            notes.append("DOE 需明确因子数与水平数，示例为 2^3 全因子，请按实际实验设计替换")
        else:
            cmds.append(f"DESCRIBE {col_list}.")

        if "export" in intent.constraints:
            cmds.append("NOTE 导出由执行层负责：COM 侧调用 SaveAs / OutputDocument.SaveAs")
        return cmds, notes

    # -------------------------------------------------------------- python gen
    def build_python(self, intent: MinitabIntent, commands: list[str]) -> str:
        body = "\n".join(f'    "{c}",' for c in commands)
        return f'''"""Auto-generated Minitab COM driver script.

intent: {json.dumps(intent.to_dict(), ensure_ascii=False)}
{TEMPLATE_MARKER}
"""
from __future__ import annotations

import pythoncom
import win32com.client
from win32com.client import gencache

COMMANDS = [
{body}
]


def main() -> int:
    pythoncom.CoInitialize()
    # gencache first (early binding), dynamic fallback for typelib-less installs
    try:
        app = gencache.EnsureDispatch("Mtb.Application")
    except Exception:
        app = win32com.client.dynamic.Dispatch("Mtb.Application")
    project = app.ActiveProject or app.New() or app.ActiveProject
    for cmd in COMMANDS:
        project.ExecuteCommand(cmd)
        print("executed:", cmd)
    if {str(intent.output_format == "report")}:
        project.Save()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
'''

    # ------------------------------------------------------------------ public
    def generate(self, intent: MinitabIntent) -> GenerationResult:
        command = intent.session_command or CATEGORY_MAP.get(
            intent.analysis_category, ("DESCRIBE", [])
        )[0]
        template = self.kb.retrieve_command_template(command)
        pitfalls = self.kb.retrieve_pitfalls(command)
        similar = self.kb.retrieve_similar(
            f"{intent.analysis_category} {' '.join(intent.target_columns)} {intent.raw_input}", top_k=3
        )
        cmds, notes = self.build_session_commands(intent)
        lines = [ln for c in cmds for ln in split_command_lines(c)]
        code = self.build_python(intent, lines)

        rationale = [f"category={intent.analysis_category} -> command={command}"]
        if len(lines) != len(cmds):
            rationale.append(
                f"multi-line expansion: {len(cmds)} logical command(s) -> {len(lines)} ExecuteCommand line(s) "
                "(Minitab 要求逐行发送，整串发送会挂起 COM 服务器)"
            )
        if template:
            rationale.append(
                f"knowledge: {template['command_name']} ({template['category']}) "
                f"reliability={template['reliability_score']:.2f} "
                f"success={template['success_count']} fail={template['failure_count']}"
            )
        for pit in pitfalls:
            rationale.append(
                f"pitfall[{pit['command']}]: {pit['error_pattern']} -> {pit['solution']} "
                f"(x{pit['occurrence_count']})"
            )
        for case in similar:
            rationale.append(
                f"similar case score={case['_score']}: {case['raw_input'][:60]!r} "
                f"cmd={case['command_used']!r} success={bool(case['success'])}"
            )
        rationale.extend(notes)
        return GenerationResult(
            session_commands=cmds,
            python_code=code,
            command_used=command,
            rationale=rationale,
            context_used={
                "template": template,
                "pitfalls": len(pitfalls),
                "similar_cases": len(similar),
            },
        )

    @staticmethod
    def write_script(code: str, path: str | Path) -> Path:
        p = Path(path)
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(code, encoding="utf-8")
        return p
